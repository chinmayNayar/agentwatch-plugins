package install

import (
	"os"
	"path/filepath"
)

// AwPS1 runs agentwatch.exe next to it with stdin passed through as UTF-8
// and always exits 0 (Copilot denies on a non-zero exit).
const AwPS1 = `# AgentWatch hook shim for PowerShell. Generated by agentwatch install.
$ErrorActionPreference = 'Continue'
[Console]::InputEncoding  = [System.Text.UTF8Encoding]::new($false)
[Console]::OutputEncoding = [System.Text.UTF8Encoding]::new($false)
$OutputEncoding           = [System.Text.UTF8Encoding]::new($false)
$exe = Join-Path $PSScriptRoot 'agentwatch.exe'
if (-not (Test-Path -LiteralPath $exe)) { $exe = Join-Path $PSScriptRoot 'agentwatch' }
$payload = [Console]::In.ReadToEnd()
if (Test-Path -LiteralPath $exe) {
  $payload | & $exe @args
}
exit 0
`

// AwSh is the POSIX equivalent (used by the Cursor plugin and by hand).
const AwSh = `#!/bin/sh
# AgentWatch hook shim. Generated by agentwatch install.
dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
exe="$dir/agentwatch"
[ -x "$exe" ] || { [ -n "$AGENTWATCH_FAIL_CLOSED_MISSING" ] && printf '%s\n' "$AGENTWATCH_FAIL_CLOSED_MISSING"; exit 0; }
exec "$exe" "$@"
`

func writeShims(dir string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "aw.ps1"), []byte(AwPS1), 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "aw.sh"), []byte(AwSh), 0o755)
}
